import { createCanvas } from '@napi-rs/canvas';
const c=createCanvas(960,540); const g=c.getContext('2d');
g.fillStyle='#000'; g.fillRect(0,0,960,540);
g.strokeStyle='#37F2FF'; g.lineWidth=2; g.beginPath(); g.moveTo(400,100); g.lineTo(400,440); g.stroke();
const rd=(ctx,x,y)=>{const d=ctx.getImageData(x,y,1,1).data;return [d[0],d[1],d[2]]};
const mk=(w,h)=>{const cc=createCanvas(w,h);return {c:cc,x:cc.getContext('2d'),w,h}};
const wide=mk(60,34), mid=mk(120,68), tmp=mk(30,17);
wide.x.globalAlpha=0.9; wide.x.drawImage(c,0,0,60,34);
wide.x.globalCompositeOperation='lighter'; wide.x.globalAlpha=0.8;
for(let i=0;i<2;i++) wide.x.drawImage(c,0,0,60,34);
wide.x.globalAlpha=1; wide.x.globalCompositeOperation='source-over';
console.log('wide px', rd(wide.x,25,17), rd(wide.x,26,17), rd(wide.x,24,17));
tmp.x.drawImage(wide.c,0,0,30,17);
wide.x.globalCompositeOperation='multiply';
wide.x.drawImage(tmp.c,0,0,60,34);
wide.x.globalCompositeOperation='source-over';
console.log('wide squared', rd(wide.x,25,17), rd(wide.x,26,17));
g.save(); g.setTransform(1,0,0,1,0,0); g.globalCompositeOperation='lighter'; g.globalAlpha=0.5;
g.drawImage(wide.c,0,0,960,540);
g.restore();
console.log('after draw', rd(g,420,270), rd(g,400,270));
